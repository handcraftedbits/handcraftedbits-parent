package com.handcraftedbits.support.api.immutables;

/// Replaces [java.util.Objects] in code generated by Immutables, so that a `null` value causes an [IllegalArgumentException] instead of
/// a [NullPointerException].
@SuppressWarnings("unused")
public final class Objects {
     private Objects () {
     }

     /// Returns whether two objects are equal, as [java.util.Objects#equals(Object, Object)] does.
     ///
     /// @param a the first object
     /// @param b the second object
     /// @return `true` if the objects are equal or both `null`
     public static boolean equals (final Object a, final Object b) {
          return java.util.Objects.equals(a, b);
     }

     /// Returns the hash code of an object, as [java.util.Objects#hashCode(Object)] does.
     ///
     /// @param object the object
     /// @return the object's hash code, or `0` if it is `null`
     public static int hashCode (final Object object) {
          return java.util.Objects.hashCode(object);
     }

     /// Returns an object after checking that it is not `null`.
     ///
     /// @param <T> the type of the object
     /// @param obj the object to check
     /// @param message the name of the value, which begins the exception message; ignored when `obj` is not `null`
     /// @return `obj`, unmodified
     /// @throws IllegalArgumentException if `obj` is `null`
     public static <T> T requireNonNull (final T obj, final String message) {
          // Immutables' generated map setters build the message lazily, passing null whenever the value is non-null. Returning early here means the
          // message is only validated when there is an actual null to report.
          if (obj != null) {
               return obj;
          }

          if (message == null || message.isBlank()) {
               throw new IllegalArgumentException("name must not be null or blank");
          }

          throw new IllegalArgumentException("%s must not be null".formatted(message));
     }
}
